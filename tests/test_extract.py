def test_every_source_paragraph_is_accounted_for():
    for src in (MSA, POLICY, CONDUCT, PORTAL, DOCX, PDF, CORPUS_001):
        if src == PDF and not E.pdf_backends():
            continue
        conv = convert(src)
        st = conv.structured
        indexes = [d.index for d in st.dispositions]
        assert sorted(indexes) == [p.index for p in st.extracted.paras], src
        assert len(indexes) == len(set(indexes)), src          # exactly once
        report = conv.report_path.read_text()
        assert f"({st.extracted.n_paras} of {st.extracted.n_paras} accounted for)" \
            in report, src
        for d in st.dispositions:
            assert f"| {d.index} | {d.kind} |" in report, (src, d.index)


def test_accounting_failure_is_a_crash_not_a_quiet_omission():
    ex = E.extract(POLICY)
    real = S._Builder.run

    def broken(self):
        clauses, disp, warn = real(self)
        return clauses, disp[:-1], warn            # "lose" one paragraph

    try:
        S._Builder.run = broken
        S.infer_structure(ex)
        raise AssertionError("expected AssertionError about accounting")
    except AssertionError as e:
        assert "accounting is broken" in str(e), e
    finally:
        S._Builder.run = real


