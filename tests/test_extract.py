# --- 1. normalisation ------------------------------------------------------


def test_normalise_typography_only():
    raw = ("“Base Hourly Rate” means the Employee’s salary "
           "divided by 2,080 — see £75.50 and 1.25 times …")
    out = E.normalise_text(raw)
    assert '"Base Hourly Rate"' in out, out
    assert "Employee's" in out, out
    assert " " not in out
    # digits, currency and words untouched
    assert "2,080" in out and "£75.50" in out and "1.25 times" in out
    assert "..." in out and "…" not in out
    # em dash is canonicalised, NOT folded to ASCII: folding would edit the text
    assert "—" in out, out
    assert "--" not in out


def test_normalise_is_idempotent_and_keeps_dash_family_canonical():
    raw = "a ‒ b ― c ‑d − e"
    once = E.normalise_text(raw)
    assert once == E.normalise_text(once)
    assert "–" in once and "—" in once      # figure dash, horizontal bar
    assert "‒" not in once and "―" not in once
    assert "-d" in once                               # non-breaking hyphen
    assert E.normalise_text("ofﬁce") == "office"  # PDF ligature restores the word
    assert E.normalise_text("soft­hyphen") == "softhyphen"


def test_paragraph_breaks_preserved_line_breaks_too():
    text = "one line\nstill clause one\n\n  (a) first item;\n  (b) second item.\n"
    paras = E.split_paragraphs(E.normalise_text(text))
    assert len(paras) == 2, [p.text for p in paras]
    assert paras[0].text == "one line\nstill clause one"
    # the sub-paragraph list is ONE paragraph whose lines stay separate
    assert paras[1].lines == ["  (a) first item;", "  (b) second item."]
    assert [p.index for p in paras] == [1, 2]


def test_dehyphenation_only_joins_broken_words():
    assert E._dehyphenate("reason-\nable") == "reasonable"
    assert E._dehyphenate("Client-\nBillable") == "Client-\nBillable"   # capital
    assert E._dehyphenate("pro-rated") == "pro-rated"


