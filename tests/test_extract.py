def test_conversion_gaps_become_conflicts_and_block_the_merge():
    d, real = isolated_ingest()
    try:
        pr = I.propose_ingestion(CONDUCT, converted_dir=d / "converted")
        kinds = {c.kind: c for c in pr.conflicts}
        assert I.ConflictKind.CONVERSION_METADATA in kinds
        assert kinds[I.ConflictKind.CONVERSION_METADATA].severity == "blocking"
        assert I.ConflictKind.CONVERSION_SYNTHESISED in kinds
        assert kinds[I.ConflictKind.CONVERSION_SYNTHESISED].severity == "advisory"
        assert not pr.mergeable and pr.unresolved
        try:
            I.merge(pr.id, corpus_dir=str(d / "corpus"))
            raise AssertionError("merge must refuse while a conflict is unresolved")
        except I.MergeRefused as e:
            assert "unresolved conflict" in str(e)
            assert "resolution" in str(e) and "resolved_by" in str(e)

        # resolving the conflict is not enough: the sentinel is still in the file
        for c in pr.conflicts:
            c.resolution = "reviewed"
            c.resolved_by = "tester"
        pr.save()
        assert I.Proposal.load(pr.id).mergeable
        try:
            I.merge(pr.id, corpus_dir=str(d / "corpus"))
            raise AssertionError("merge must refuse on the NEEDS-HUMAN sentinel")
        except I.MergeRefused as e:
            assert S.NEEDS_HUMAN in str(e)
            assert "not clearable by a resolution" in str(e)
    finally:
        I.PROPOSALS = real


