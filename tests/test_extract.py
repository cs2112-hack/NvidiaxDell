"""Tests for lks.extract, lks.structure, and the conversion path in lks.ingest.

There is no pytest in this checkout, so this is a runnable script: plain
asserts, one function per property, and a `__main__` block that runs them all
and reports. Run it with

    . scripts/env.sh && $PY tests/test_extract.py

Every test that writes anything writes to a temporary directory. The two
binary fixtures (.docx, .pdf) are generated by their own generators under
tests/fixtures/ so that nothing opaque is committed.

The load-bearing test is `test_corpus_roundtrip`: every corpus document is run
through extraction and structure inference, and the result must segment to the
same clause ids with the same content hashes. A conversion that changes an
existing corpus document is wrong, whatever else it gets right.
"""
