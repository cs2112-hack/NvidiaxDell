def test_numbered_clauses_without_decimals():
    """`7. The Supplier shall ...` -- the number is the clause's, and the
    house convention's section-relative id keeps it citable as "7"."""
    f = tmpdir() / "purchase-conditions.txt"
    f.write_text(
        "PURCHASE CONDITIONS\n\n"
        "1. The Supplier shall deliver the Goods to the address in the Order.\n\n"
        "2. The Company shall pay each invoice within 30 days of receipt.\n\n"
        "3. Where the Supplier delivers late, the Company may reject the Goods\n"
        "and recover any pre-payment.\n\n"
        "4. Either party may terminate on 30 days' written notice.\n"
    )
    conv = convert(f)
    st = conv.structured
    assert st.scheme.clause_layer == "numbered", st.scheme
    assert st.scheme.name == "numbered-clauses"
    assert [c.clause_id for c in st.clauses] == ["CL-1.1", "CL-2.1", "CL-3.1", "CL-4.1"]
    assert [c.document_number for c in st.clauses] == ["1", "2", "3", "4"]
    assert all(c.id_source == "derived" for c in st.clauses)
    assert all(not c.synthesised for c in st.clauses)
    assert st.meta["title"] == "PURCHASE CONDITIONS"
    doc = parse_document(conv.converted_path)
    assert doc.clause("CL-3.1").body.startswith("Where the Supplier delivers late")


